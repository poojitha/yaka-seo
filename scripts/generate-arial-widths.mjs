// Generates src/main/arial-widths.ts: Arial's advance widths (font units) for the characters page titles and
// descriptions commonly use. Reads the font's cmap and hmtx tables directly, so no font library is needed.
// Usage: node scripts/generate-arial-widths.mjs [path/to/arial.ttf]   (defaults to the Windows copy)
import { readFileSync, writeFileSync } from 'node:fs';

const fontPath = process.argv[2] ?? 'C:/Windows/Fonts/arial.ttf';
const buf = readFileSync(fontPath);

const tables = {};
for (let i = 0; i < buf.readUInt16BE(4); i++) {
    const o = 12 + i * 16;
    tables[buf.toString('ascii', o, o + 4)] = buf.readUInt32BE(o + 8);
}
const unitsPerEm = buf.readUInt16BE(tables.head + 18);
const numHMetrics = buf.readUInt16BE(tables.hhea + 34);
const advance = (glyph) => buf.readUInt16BE(tables.hmtx + Math.min(glyph, numHMetrics - 1) * 4);

// cmap subtable format 4 for platform 3 (Windows), encoding 1 (Unicode BMP).
let sub = -1;
for (let i = 0; i < buf.readUInt16BE(tables.cmap + 2); i++) {
    const r = tables.cmap + 4 + i * 8;
    if (buf.readUInt16BE(r) === 3 && buf.readUInt16BE(r + 2) === 1) sub = tables.cmap + buf.readUInt32BE(r + 4);
}
if (sub < 0) throw new Error('No Windows Unicode cmap in this font');
const segX2 = buf.readUInt16BE(sub + 6);
const ends = sub + 14;
const starts = ends + segX2 + 2;
const deltas = starts + segX2;
const rangeOffsets = deltas + segX2;
function glyphFor(code) {
    for (let i = 0; i < segX2 / 2; i++) {
        if (code > buf.readUInt16BE(ends + i * 2)) continue;
        const start = buf.readUInt16BE(starts + i * 2);
        if (code < start) return 0;
        const delta = buf.readInt16BE(deltas + i * 2);
        const ro = buf.readUInt16BE(rangeOffsets + i * 2);
        if (ro === 0) return (code + delta) & 0xffff;
        const g = buf.readUInt16BE(rangeOffsets + i * 2 + ro + (code - start) * 2);
        return g === 0 ? 0 : (g + delta) & 0xffff;
    }
    return 0;
}

// Latin (ASCII, Latin-1, Extended-A), Greek, Cyrillic, and common typographic punctuation and symbols.
const RANGES = [
    [0x20, 0x7e],
    [0xa0, 0x17f],
    [0x370, 0x3ff],
    [0x400, 0x45f],
    [0x2010, 0x2027],
    [0x2030, 0x203a],
    [0x20ac, 0x20ac],
    [0x2122, 0x2122],
];

const lines = RANGES.map(([from, to]) => {
    // 0 marks a character Arial doesn't have; the measuring code falls back to an estimate.
    const widths = [];
    for (let c = from; c <= to; c++) {
        const g = glyphFor(c);
        widths.push(g === 0 ? 0 : advance(g));
    }
    return `    [0x${from.toString(16)}, [${widths.join(', ')}]],`;
});

const out = `// Generated by scripts/generate-arial-widths.mjs from Arial (${unitsPerEm} units per em). Do not edit by hand.

export const ARIAL_UNITS_PER_EM = ${unitsPerEm};

/** [first code point, advance widths in font units for consecutive code points]; 0 = not in Arial. */
export const ARIAL_ADVANCES: [number, number[]][] = [
${lines.join('\n')}
];
`;
writeFileSync(new URL('../src/main/arial-widths.ts', import.meta.url), out);
console.log(`Wrote src/main/arial-widths.ts (${RANGES.length} ranges)`);
